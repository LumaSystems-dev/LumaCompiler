// Разрешение import'ов (Luma 0.1.1): проход ПОСЛЕ парсера и ДО анализатора.
//
// import "path.luma"; заменяется последовательностью стейтментов модуля,
// подставленной в точку импорта (компиляционный инлайн):
//   * путь — строковый литерал, разрешается ОТНОСИТЕЛЬНО ДИРЕКТОРИИ
//     импортирующего файла;
//   * каждый файл обрабатывается один раз: повторный import того же файла
//     (в т.ч. из других модулей) — no-op;
//   * циклы (a → b → a) обнаруживаются, ошибка показывает всю цепочку;
//   * конфликт одинаковых глобальных имён из двух модулей ловит Analyzer
//     уже на склеенной программе ("Variable 'x' is already defined");
//   * import разрешён только на верхнем уровне модуля.
//
// После этого прохода узлов ImportStmt в дереве не остаётся: анализатор,
// компилятор и VM ничего об import не знают, а .lbc самодостаточен —
// исходники модулей во время исполнения не нужны.
Program resolveImports(Program program, const std::string& sourcePath);
